    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
       try {
            
            int matricula = 0;
            if (!txtMatricula.getText().trim().isEmpty()) {
                matricula = Integer.parseInt(txtMatricula.getText().trim());
            }
            List<Alumno> lista = alumnoService.queryToDataBase(dbCon, matricula);

            if (lista == null || lista.isEmpty()) {
                JOptionPane.showMessageDialog(this, "No se encontraron alumnos.");
                return;
            }
            if (matricula != 0) {
                Alumno a = lista.get(0);
                txtNombre.setText(a.getNombre());
                txtApellido.setText(a.getApellido());
                txtEdad.setText(String.valueOf(a.getEdad()));
                txtCorreo.setText(a.getCorreo());
            } else {
               
                StringBuilder mensaje = new StringBuilder("--- LISTA DE ALUMNOS ---\n\n");
                for (Alumno a : lista) {
                    mensaje.append("Matrícula: ").append(a.getIdAlumno())
                           .append(" | Nombre: ").append(a.getNombre()).append(" ").append(a.getApellido())
                           .append(" | Edad: ").append(a.getEdad())
                           .append(" | Correo: ").append(a.getCorreo())
                           .append("\n");
                }
                JOptionPane.showMessageDialog(this, mensaje.toString());
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La matrícula debe ser un número entero.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al consultar: " + e.getMessage());
        }        
    }//GEN-LAST:event_btnConsultarActionPerformed

