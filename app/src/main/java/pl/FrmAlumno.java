    private void btnInsertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertActionPerformed
        if (txtNombre.getText().trim().isEmpty() || txtApellido.getText().trim().isEmpty() 
                || txtEdad.getText().trim().isEmpty() || txtCorreo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor llena todos los campos.");
            return; // Este 'return' corta el método aquí y ya no entra al try
        }

        try {
            Alumno alumno = new Alumno();
            alumno.setNombre(txtNombre.getText().trim());
            alumno.setApellido(txtApellido.getText().trim());
            alumno.setEdad(Integer.parseInt(txtEdad.getText().trim()));
            alumno.setCorreo(txtCorreo.getText().trim());

            int aux = alumnoService.insertToDataBase(dbCon, alumno);

            if (aux == 1) {
                JOptionPane.showMessageDialog(this, "¡Alumno registrado con éxito!");
                txtNombre.setText("");
                txtApellido.setText("");
                txtEdad.setText("");
                txtCorreo.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo registrar el alumno.");
            }
        } catch (NumberFormatException e) {
            // Aquí solo entrará si escribiste letras en edad (ej. "veinte")
            JOptionPane.showMessageDialog(this, "La edad debe ser un número.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnInsertActionPerformed

    private void btnUpdatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdatActionPerformed
       if (txtMatricula.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty() 
                || txtApellido.getText().trim().isEmpty() || txtEdad.getText().trim().isEmpty() 
                || txtCorreo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Para actualizar llena Matrícula y todos los datos.");
            return;
        }

        try {
            Alumno alumno = new Alumno();
            alumno.setIdAlumno(Integer.parseInt(txtMatricula.getText().trim()));
            alumno.setNombre(txtNombre.getText().trim());
            alumno.setApellido(txtApellido.getText().trim());
            alumno.setEdad(Integer.parseInt(txtEdad.getText().trim()));
            alumno.setCorreo(txtCorreo.getText().trim());

            int aux = alumnoService.updateToDataBase(dbCon, alumno);

            if (aux == 1) {
                JOptionPane.showMessageDialog(this, "¡Alumno actualizado con éxito!");
               
                int matricula = Integer.parseInt(txtMatricula.getText().trim());
                List<Alumno> lista = alumnoService.queryToDataBase(dbCon, matricula);
                StringBuilder mensaje = new StringBuilder("--- LISTA DE ALUMNOS ---\n\n");
                for (Alumno a : lista) {
                    mensaje.append("Matrícula: ").append(a.getIdAlumno())
                           .append(" | Nombre: ").append(a.getNombre()).append(" ").append(a.getApellido())
                           .append(" | Edad: ").append(a.getEdad())
                           .append(" | Correo: ").append(a.getCorreo())
                           .append("\n");
                }
                JOptionPane.showMessageDialog(this, mensaje.toString());
                limpiarCampos();
               
                
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo actualizar. Verifica que la matrícula exista.");
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Matrícula y Edad deben ser números enteros.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUpdatActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
       if (txtMatricula.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Escribe la matrícula del alumno a eliminar.");
            return;
        }

        try {
            int matricula = Integer.parseInt(txtMatricula.getText().trim());
            int confirmacion = JOptionPane.showConfirmDialog(this, 
                    "¿Seguro que deseas eliminar al alumno con matrícula " + matricula + "?", 
                    "Confirmar eliminación", 
                    JOptionPane.YES_NO_OPTION);

            if (confirmacion == JOptionPane.YES_OPTION) {
                int aux = alumnoService.deleteToDataBase(dbCon, matricula);

                if (aux == 1) {
                    JOptionPane.showMessageDialog(this, "¡Alumno eliminado!");
                    limpiarCampos();
                } else {
                    JOptionPane.showMessageDialog(this, "No se pudo eliminar. Verifica que la matrícula exista.");
                }
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "La matrícula debe ser un número entero.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        } 
    }//GEN-LAST:event_btnEliminarActionPerformed

